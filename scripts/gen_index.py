#!/usr/bin/env python3
"""Regenerate the atomic-page section of wiki/INDEX.md from page frontmatter.

Usage: python3 scripts/gen_index.py
Replaces everything between the atomic-pages:start/end markers.
"""
import glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATS = [("reference", "Reference (timeline, matrix, checklist, glossary, reading list, people)"),
        ("concept", "Concepts"), ("technology", "Technologies"),
        ("money-rail", "Money rails"), ("compute", "Compute sources"),
        ("organism", "Organisms and agent projects"),
        ("research", "Research (self-improvement, alife, replication evals)"),
        ("attack", "Attacks and kill vectors"),
        ("actor", "Actors (people and organisations)"),
        ("open-problem", "Open problems"),
        ("history", "History and lineage"),
        ("legal", "Legal wrappers (as survival tools)"),
        ("fiction", "Fiction and thought experiments (design references)")]

def gist(text):
    blk = []
    for line in text.split("\n"):
        if line.startswith("> "):
            blk.append(line[2:])
        elif blk:
            break
    txt = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", " ".join(blk))
    first = re.split(r"(?<=[.!?])\s", txt)[0]
    if len(first) > 150:
        first = first[:147].rsplit(" ", 1)[0] + "…"
    return first.replace("|", "/")

def main():
    pages = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "wiki", "pages", "*.md"))):
        s = open(f).read()
        m = re.search(r"^category:\s*(\S+)", s, re.M)
        if not m:
            continue
        title = re.search(r'^title:\s*"?(.*?)"?$', s, re.M).group(1)
        pages.setdefault(m.group(1), []).append((os.path.basename(f)[:-3], title, gist(s)))
    out = ["<!-- atomic-pages:start (generated by scripts/gen_index.py; do not hand-edit) -->", "",
           "# Atomic pages", "",
           "One concept per page, densely linked. Conventions: [SCHEMA](SCHEMA.md). "
           "Bibliography: [sources](sources.md).", ""]
    for cat, head in CATS:
        rows = pages.get(cat, [])
        out += [f"## {head}", "", f"{len(rows)} pages.", "", "| Page | Gist |", "|---|---|"]
        out += [f"| [{t}](pages/{n}.md) | {g} |" for n, t, g in rows]
        out.append("")
    out.append("<!-- atomic-pages:end -->")
    p = os.path.join(ROOT, "wiki", "INDEX.md")
    s = open(p).read()
    s = re.sub(r"<!-- atomic-pages:start.*?<!-- atomic-pages:end -->", "\n".join(out), s, flags=re.S)
    open(p, "w").write(s)
    print({c: len(pages.get(c, [])) for c, _ in CATS})

if __name__ == "__main__":
    main()
