#!/usr/bin/env python3
"""Lint the wiki and regenerate wiki/sources.md.

Usage:
  python3 scripts/wiki_lint.py            # lint only (exit 1 on errors)
  python3 scripts/wiki_lint.py --sources  # also rewrite wiki/sources.md
  python3 scripts/wiki_lint.py --external # also HEAD-check external URLs (slow)

Rules (see wiki/SCHEMA.md):
  * every relative markdown link in the repo resolves to an existing file
  * atomic pages (frontmatter has `category:`) carry title/category/status/updated
    and the required sections, and are listed in wiki/INDEX.md
  * public-safety strings never appear in wiki/ or docs/
"""
import os, re, sys, glob, datetime, collections, urllib.request, urllib.error, concurrent.futures

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = os.path.join(ROOT, "wiki", "pages")
CATEGORIES = ["concept", "technology", "money-rail", "compute", "organism",
              "research", "attack", "actor", "open-problem"]
REQUIRED_SECTIONS = ["## How it serves the organism", "## How it fails",
                     "## Related", "## Sources"]
FORBIDDEN = [r"[Bb]itstamp", r"/workspace/", r"/cursor/stores", r"/home/box",
             r"store-[0-9a-f]{8}-", r"enclava\.dev (is|has) (launched|live)",
             r"[Ee]nclava (is|has) launched"]
LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
URL = re.compile(r"https?://[^\s)>\]`\"']+")

def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    fm = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith(" "):
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"')
    return fm

def md_files():
    for p in glob.glob(os.path.join(ROOT, "**", "*.md"), recursive=True):
        if "/node_modules/" in p or "/.git/" in p:
            continue
        yield p

def main():
    errors, warns = [], []
    index = open(os.path.join(ROOT, "wiki", "INDEX.md")).read()
    sources = collections.defaultdict(set)
    for path in md_files():
        rel = os.path.relpath(path, ROOT)
        text = open(path).read()
        body = re.sub(r"```.*?```", "", text, flags=re.S)
        body = re.sub(r"`[^`\n]*`", "", body)
        for target in LINK.findall(body):
            if re.match(r"^(https?:|mailto:|#)", target):
                continue
            t = target.split("#")[0]
            if not t:
                continue
            dest = os.path.normpath(os.path.join(os.path.dirname(path), t))
            if not os.path.exists(dest):
                errors.append(f"{rel}: broken link -> {target}")
        if rel.startswith(("wiki/", "docs/")) and rel != "wiki/SCHEMA.md":
            for pat in FORBIDDEN:
                if re.search(pat, text):
                    errors.append(f"{rel}: forbidden string /{pat}/")
        fm = frontmatter(text)
        if rel.startswith("wiki/pages/") and "category" in fm:
            for k in ("title", "category", "status", "updated"):
                if not fm.get(k):
                    errors.append(f"{rel}: missing frontmatter `{k}`")
            if fm.get("category") not in CATEGORIES:
                errors.append(f"{rel}: unknown category {fm.get('category')}")
            for s in REQUIRED_SECTIONS:
                if s not in text:
                    errors.append(f"{rel}: missing section '{s}'")
            if not re.search(r"^> ", text, re.M):
                errors.append(f"{rel}: missing '> ' one-paragraph summary")
            name = os.path.basename(path)
            if f"pages/{name}" not in index:
                errors.append(f"{rel}: not listed in wiki/INDEX.md (orphan)")
            src = text.split("## Sources", 1)[-1]
            if not URL.search(src) and "docs/" not in src:
                errors.append(f"{rel}: Sources section has no URL or docs/ link")
            for u in URL.findall(src):
                sources[u.rstrip(".,;")].add(name[:-3])
    if "--sources" in sys.argv:
        write_sources(sources)
    if "--external" in sys.argv:
        check_external(sorted(sources), warns)
    for w in warns:
        print("WARN", w)
    for e in errors:
        print("ERROR", e)
    print(f"{len(errors)} errors, {len(warns)} warnings, {len(sources)} cited URLs")
    sys.exit(1 if errors else 0)

def write_sources(sources):
    by_host = collections.defaultdict(list)
    for u, pages in sources.items():
        host = re.sub(r"^www\.", "", u.split("/")[2])
        by_host[host].append((u, sorted(pages)))
    out = ["---", "title: Sources — bibliography (generated)", f"updated: {datetime.date.today().isoformat()}", "---", "",
           "# Sources", "",
           "Generated by `python3 scripts/wiki_lint.py --sources` from the `## Sources`",
           "section of every atomic page. Do not edit by hand; edit the page and re-run.",
           f"{len(sources)} URLs from {len(by_host)} hosts.", ""]
    for host in sorted(by_host):
        out.append(f"## {host}")
        out.append("")
        for u, pages in sorted(by_host[host]):
            links = ", ".join(f"[{p}](pages/{p}.md)" for p in pages)
            out.append(f"- <{u}> — {links}")
        out.append("")
    open(os.path.join(ROOT, "wiki", "sources.md"), "w").write("\n".join(out))

def check_external(urls, warns):
    def head(u):
        for method in ("HEAD", "GET"):
            try:
                req = urllib.request.Request(u, method=method,
                      headers={"User-Agent": "Mozilla/5.0 wiki-lint"})
                return u, urllib.request.urlopen(req, timeout=20).status
            except urllib.error.HTTPError as e:
                code = e.code
                if method == "GET":
                    return u, code
            except Exception as e:
                if method == "GET":
                    return u, str(e)[:60]
        return u, "?"
    with concurrent.futures.ThreadPoolExecutor(16) as ex:
        for u, code in ex.map(head, urls):
            if code != 200:
                warns.append(f"{code} {u}")

if __name__ == "__main__":
    main()
